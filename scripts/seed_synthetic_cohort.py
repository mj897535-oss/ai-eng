"""Synthetic Cohort Generator for Demos & Reproducibility (Phase P16).

RESEARCH INTEGRITY RULE:
All data generated by this script is clearly and explicitly labelled as
[SYNTHETIC DEMO DATA] across all fields, research codes, and model notes.
Produces a realistic cohort of 120 participants across intervention and control groups.
"""

from __future__ import annotations

import asyncio
import os
import random
import sys
import uuid
from datetime import datetime, timedelta
from pathlib import Path

# Add apps/api to path
sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "apps" / "api"))

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine

from app.core.config import settings
from app.models.assessment import Assessment, AssessmentTask, AssessmentType, ErrorAnnotation
from app.models.consent import Consent, ConsentStatus
from app.models.identity import User, UserRole
from app.models.practice import AttemptType, PracticeEvent, PracticeSession, UtterancePattern
from app.models.research import Participant, StudyGroup


SYNTHETIC_FIRST_NAMES = [
    "Aarav", "Vivaan", "Aditya", "Vihaan", "Arjun", "Sai", "Reyansh", "Ayaan", "Krishna", "Ishaan",
    "Diya", "Saanvi", "Aanya", "Aadhya", "Pari", "Ananya", "Myra", "Riya", "Avani", "Ira"
]

SYNTHETIC_LAST_NAMES = [
    "Sharma", "Verma", "Patel", "Reddy", "Rao", "Nair", "Iyer", "Gupta", "Mehta", "Singh"
]

SYNTHETIC_TOPICS = [
    "Describe your morning routine before heading to work or college.",
    "Talk about a memorable journey you took with your family.",
    "Explain how to prepare your favorite traditional dish.",
    "Discuss the advantages and challenges of online learning.",
]

ERROR_TEMPLATES = [
    ("TNS", "Yesterday I go to market", "went", "Simple past tense required for past completed action."),
    ("SVA", "The teacher teach well", "teaches", "Singular third-person subject takes singular verb form."),
    ("WO", "I always am happy", "am always", "Frequency adverb typically follows auxiliary or BE verb."),
    ("AUX", "He does can speak English", "can", "Modal verb replaces auxiliary do in affirmative statements."),
    ("ART", "I saw a elephant yesterday", "an", "Indefinite article 'an' required before vowel sounds."),
    ("PREP", "She is good in English", "good at", "Adjective 'good' collocates with preposition 'at' for skills."),
    ("PRO", "Me and him went to library", "He and I", "Subject pronouns required in subject position."),
]


async def seed_synthetic_cohort(cohort_size: int = 120, db_url: str | None = None) -> None:
    print(f"Generating realistic SYNTHETIC cohort of {cohort_size} participants...")
    
    # Use SQLite file if PostgreSQL not explicitly provided or offline
    url = db_url or os.getenv("SYNTHETIC_DATABASE_URL", "sqlite+aiosqlite:///d:/syntaxlens/synthetic_demo.db")
    print(f"Using database: {url}")
    
    engine = create_async_engine(
        url,
        echo=False,
        execution_options={"schema_translate_map": {"identity": None, "research": None}},
    )
    
    from app.models.base import Base
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)

    session_factory = async_sessionmaker(engine, expire_on_commit=False)

    async with session_factory() as db:
        # 1. Create standard tasks if missing
        tasks = []
        for i, text in enumerate(SYNTHETIC_TOPICS, 1):
            t = AssessmentTask(
                task_id=uuid.uuid4(),
                title=f"Synthetic Task {i}",
                prompt_text=text,
                equivalence_group="synthetic_group_A" if i % 2 == 1 else "synthetic_group_B",
                rubric_version="v1.0-jam-phd",
            )
            tasks.append(t)
            db.add(t)
        await db.flush()

        base_date = datetime.utcnow() - timedelta(days=21)

        for idx in range(1, cohort_size + 1):
            fname = random.choice(SYNTHETIC_FIRST_NAMES)
            lname = random.choice(SYNTHETIC_LAST_NAMES)
            full_name = f"[SYNTHETIC] {fname} {lname}"
            email = f"synthetic.p{idx:03d}@demo.syntaxlens.local"
            code = f"SYNTH-{idx:03d}"
            group = StudyGroup.INTERVENTION if idx % 2 == 1 else StudyGroup.CONTROL

            user = User(
                id=uuid.uuid4(),
                email=email,
                full_name=full_name,
                hashed_password="synthetic_hash_demo",
                role=UserRole.PARTICIPANT,
                is_active=True,
            )
            db.add(user)
            await db.flush()

            part = Participant(
                participant_id=uuid.uuid4(),
                user_id=user.id,
                research_code=code,
                study_group=group,
                age=random.randint(19, 26),
                age_band="18-24" if idx % 3 != 0 else "25-34",
                mother_tongue=random.choice(["Hindi", "Telugu", "Tamil", "Marathi", "Bengali"]),
                school_medium=random.choice(["English", "Regional", "Bilingual"]),
                country="India",
                is_active=True,
                is_withdrawn=False,
            )
            db.add(part)
            await db.flush()

            # Informed Consent
            consent = Consent(
                consent_id=uuid.uuid4(),
                participant_id=part.participant_id,
                consent_version="v1.0-synthetic-demo",
                status=ConsentStatus.CONSENTED,
            )
            db.add(consent)

            # Pre-test Assessment
            pre_task = tasks[0]
            pre_words = random.randint(110, 160)
            pre_asmt = Assessment(
                assessment_id=uuid.uuid4(),
                participant_id=part.participant_id,
                task_id=pre_task.task_id,
                assessment_type=AssessmentType.PRE,
                status="completed",
                audio_key=f"audio/{code}/pre_test_synth.webm",
                transcript=f"[SYNTHETIC TRANSCRIPT] Yesterday I go to market and I see my friend.",
                word_count=pre_words,
                stt_version="mock-stt-v1",
                rubric_version="v1.0-jam-phd",
                prompt_version="v1.0-assessor",
                model_version="mock-syntax-v1",
                is_verified=True,
                is_official=True,
            )
            db.add(pre_asmt)
            await db.flush()

            # Pre-test Error Annotations
            for cat, error_str, corr_str, expl in random.sample(ERROR_TEMPLATES, random.randint(2, 4)):
                ann = ErrorAnnotation(
                    annotation_id=uuid.uuid4(),
                    assessment_id=pre_asmt.assessment_id,
                    start_char=10,
                    end_char=20,
                    candidate_error=error_str,
                    suggested_correction=corr_str,
                    category_code=cat,
                    explanation=f"[SYNTHETIC DEMO] {expl}",
                    confidence=0.92,
                    ai_status="candidate",
                    flag="candidate_error",
                    model_version="mock-syntax-v1",
                )
                db.add(ann)

            # Practice Sessions for Intervention Group
            if group == StudyGroup.INTERVENTION:
                for s_num in range(1, random.randint(3, 6)):
                    session = PracticeSession(
                        session_id=uuid.uuid4(),
                        participant_id=part.participant_id,
                        tutor_prompt_version="v1.0-tutor",
                        topic="Daily Routines & Hobbies",
                        target_categories_json='["TNS", "SVA"]',
                        active_duration_seconds=random.randint(600, 950),
                        idle_duration_seconds=random.randint(30, 80),
                        status="completed",
                    )
                    db.add(session)

            # Post-test Assessment (for 85% of cohort who completed post-test)
            if idx <= int(cohort_size * 0.85):
                post_task = tasks[1]
                post_words = random.randint(120, 175)
                post_asmt = Assessment(
                    assessment_id=uuid.uuid4(),
                    participant_id=part.participant_id,
                    task_id=post_task.task_id,
                    assessment_type=AssessmentType.POST,
                    status="completed",
                    audio_key=f"audio/{code}/post_test_synth.webm",
                    transcript=f"[SYNTHETIC TRANSCRIPT] When I went to market, I saw my friend.",
                    word_count=post_words,
                    stt_version="mock-stt-v1",
                    rubric_version="v1.0-jam-phd",
                    prompt_version="v1.0-assessor",
                    model_version="mock-syntax-v1",
                    is_verified=True,
                    is_official=True,
                )
                db.add(post_asmt)
                await db.flush()

                # Fewer errors in post-test for intervention
                num_post_errors = random.randint(0, 2) if group == StudyGroup.INTERVENTION else random.randint(2, 4)
                if num_post_errors > 0:
                    for cat, error_str, corr_str, expl in random.sample(ERROR_TEMPLATES, num_post_errors):
                        post_ann = ErrorAnnotation(
                            annotation_id=uuid.uuid4(),
                            assessment_id=post_asmt.assessment_id,
                            start_char=8,
                            end_char=18,
                            candidate_error=error_str,
                            suggested_correction=corr_str,
                            category_code=cat,
                            explanation=f"[SYNTHETIC DEMO] {expl}",
                            confidence=0.94,
                            ai_status="candidate",
                            flag="candidate_error",
                            model_version="mock-syntax-v1",
                        )
                        db.add(post_ann)

        await db.commit()
    print(f"Successfully generated and committed {cohort_size} synthetic participants!")


if __name__ == "__main__":
    asyncio.run(seed_synthetic_cohort(120))
